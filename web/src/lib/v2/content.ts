/* 03 — about ------------------------------------------------------------- */
export const V2_ABOUT = {
  eyebrow: ABOUT.eyebrow,
  body: ABOUT.body,
  stat: ABOUT.stat,
  statSuffix: ABOUT.statSuffix,
  statTail: ABOUT.statTail,
  /**
   * FOUR points now, against three supplied marks — the copy gained
   * "Enterprise-Ready Integrations" and `home-content.ts` deliberately leaves
   * its `icon` off rather than reusing one of the other three. So `icon` is
   * read defensively here and the component falls back to a drawn glyph.
   *
   * `filled` is derived from the FILE, not from a position in the array. The
   * supplied marks have their stroke colour baked in rather than using
   * `currentColor`, and `2nd.svg` is drawn in WHITE because it is meant to
   * sit on a filled disc — reorder the array and this still puts the white
   * icon on the only ground it can be seen against.
   */
  points: ABOUT.points.map((point) => {
    const icon = "icon" in point ? point.icon : undefined;
    return { ...point, icon, filled: icon === "/2nd.svg" };
  }),
} as const;

