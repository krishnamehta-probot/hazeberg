/**
 * Home v2 — layout data.
 *
 * **This file no longer restates a single line of copy.** Every string comes
 * from `lib/home-content.ts`, the same module the main home page renders
 * from, and this file only adds what is genuinely v2's: which photograph a
 * card uses, which cell is filled amber, which engagement opens first.
 *
 * That is a change from the first cut, and the reason is the obvious one. v2
 * originally held its own copy of the client's copy, and the two drifted
 * almost immediately — v2 was still running the untrimmed 27-word hero lead
 * that v1 had cut to two thirds, plus a paragraph transcribed off the design
 * comp that the copy document never contained. A second copy of the copy is
 * how one of them goes stale, exactly as a second copy of a phone number is.
 * The same argument already governs `CONTACT` and `OFFICES` in the footer.
 *
 * So: the COMP governs layout, `home-content.ts` governs words. Change the
 * copy in one place and both versions move together.
 *
 * What is still local to this file, and why:
 *
 *   images     which frame sits on which card. A property of this layout —
 *              v1 uses a different set in different places
 *   tone       which cells are filled amber, blue, or left white. Design
 *   featured   which engagement is open on arrival. Design
 *   nav        v2 renders its own header, though every destination is the
 *              signed-off sitemap's
 *   footer     the lockup line and the column headings, which are structure
 *              rather than prose
 */

